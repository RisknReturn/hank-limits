def write_outputs(prefix, env, info, runs, results, args, msets):
    rows = []
    for key, res in results['designs'].items():
        kind, suite = DESIGNS[key]
        for i, t in res['table'].items():
            for g, v in t['groups'].items():
                (h1, x1), (h2, x2) = v['headline']
                (_, b1), (_, b2) = v['headline_baseline']
                rows.append(dict(design=key, mutant_set=kind, suite=suite, id=i,
                                 category=t['category'], target=t['target'], group=g,
                                 reached=v['reached'], affected_max_rel_change=v['affected'],
                                 predicted=v['predicted'], detected=v['detected'],
                                 prediction_ok=v['prediction_ok'], modes=';'.join(v['modes']),
                                 n_tests=v['n_tests'], n_changed=len(v['changed']),
                                 changed_tests=';'.join(c['test'] for c in v['changed']),
                                 metric1=h1, value1=x1, baseline1=b1, metric2=h2, value2=x2,
                                 baseline2=b2,
                                 first_message=v['changed'][0]['message'] if v['changed'] else ''))
    if rows:
        with open(prefix + '.csv', 'w', newline='') as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0]))
            w.writeheader()
            w.writerows(rows)
    store = {k: dict(pytest_summary=r.get('pytest_summary'), wall_s=r.get('wall_s'),
                     fixtures=r['fixtures'], outcomes=r['outcomes']) for k, r in runs.items()}
    mut = {kind: [{k: v for k, v in m.items() if k != 'patches'} |
                  dict(patches=[dict(file=p[0], old=p[1], new=p[2]) for p in m['patches']])
                  for m in ms] for kind, ms in msets.items()}
    with open(prefix + '.json', 'w') as f:
        json.dump(_clean(dict(environment=env, suites=info, settings=vars(args), mutants=mut,
                              reanchored={f'{s}/{i}': [dict(file=p[0], old=p[1], new=p[2]) for p in ps]
                                          for (s, i), ps in REANCHOR.items()},
                              runs=store, results=results)), f, indent=1)


