def mutant_set(kind):
    """v0.2: list of dicts with id, category, target, change, patches, reach, conf, why and the
    predictions per suite (keys pred_<suite> = {group: 'catch' | 'miss' | '?'})."""
    out = []
    if kind == 'v0.2':
        for m in MUTANTS:
            d = dict(m)
            for suite, key in (('v0.2.1', 'v021'), ('v0.3', 'v03')):
                ex, un = set(_groups(m[f'expect_{key}'])), set(_groups(m.get(f'unsure_{key}', '')))
                d[f'pred_{suite}'] = {g: ('catch' if g in ex else '?' if g in un else 'miss')
                                      for g in GROUPS}
            out.append(d)
        return out
    obs = _v01_observed()
    for m in _v01_module().MUTANTS:
        d = {k: m[k] for k in ('id', 'category', 'target', 'change', 'patches', 'reach', 'conf', 'why')}
        pv = PRED_V01_V.get(m['id'], ('?', ''))
        d['pred_v0.3'] = {g: ('catch' if obs.get(m['id'], {}).get(g) else 'miss') for g in GROUPS[:-1]}
        d['pred_v0.3']['V'] = pv[0]
        d['why_V'] = pv[1]
        out.append(d)
    return out


def _patches_for(m, suite):
    return [tuple(p) for p in REANCHOR.get((suite, m['id']), m['patches'])]


def analyse(runs, suite, mutants):
    """Per mutant and group: reached, detected, predicted, modes, changed tests (v0.1 rule)."""
    base = runs[f'{suite}/B0']
    base_out = {k: v['outcome'] for k, v in base['outcomes'].items()}
    table = {}
    for m in mutants:
        r = runs.get(f"{suite}/{m['id']}")
        if r is None:
            continue
        reach = set(_groups(m['reach']))
        pred = m[f'pred_{suite}']
        per = {}
        for g in GROUPS:
            ids = [k for k in base_out if TEST_FILE_GROUP.get(k.split('::')[0].split('/')[-1]) == g]
            if not ids:
                continue
            changed = []
            for k in ids:
                rec = r['outcomes'].get(k, dict(outcome='missing', message=''))
                if rec['outcome'] != base_out[k]:
                    changed.append(dict(test=k.split('::')[-1], baseline=base_out[k],
                                        outcome=rec['outcome'], mode=_mode(rec),
                                        message=rec['message']))
            detected = bool(changed)
            p = pred.get(g, '?')
            # V tests read the t1..t5 check results, so V is reached when any of T1..T5 is
            reached = g in reach or (g == 'V' and bool(reach & {'T1', 'T2', 'T3', 'T4', 'T5'}))
            per[g] = dict(reached=reached,
                          affected=_max_rel_change(r, base, g), predicted=p, detected=detected,
                          prediction_ok=None if p == '?' else (detected == (p == 'catch')),
                          modes=sorted({c['mode'] for c in changed}), n_tests=len(ids),
                          changed=changed, headline=_headline(g, r['fixtures']),
                          headline_baseline=_headline(g, base['fixtures']))
        table[m['id']] = dict(category=m['category'], target=m['target'], change=m['change'],
                              conf=m['conf'], detected_any=any(v['detected'] for v in per.values()),
                              detected_groups=[g for g, v in per.items() if v['detected']],
                              groups=per, pytest_summary=r.get('pytest_summary'),
                              wall_s=r.get('wall_s'))
    mut = [m for m in mutants if m['category'] != 'control' and m['id'] in table]
    groups = [g for g in GROUPS if any(g in table[m['id']]['groups'] for m in mut)]
    rates = {}
    for g in groups:
        reached = [m['id'] for m in mut if table[m['id']]['groups'][g]['reached']]
        caught = [i for i in reached if table[i]['groups'][g]['detected']]
        caught_all = [m['id'] for m in mut if table[m['id']]['groups'][g]['detected']]
        rates[g] = dict(caught=len(caught_all), of_all=len(mut), caught_reached=len(caught),
                        reached=len(reached), caught_ids=caught_all)
    cats = {}
    for m in mut:
        c = cats.setdefault(m['category'], dict(n=0, caught=0, ids_missed=[], by_group={g: 0 for g in groups}))
        c['n'] += 1
        c['caught'] += table[m['id']]['detected_any']
        if not table[m['id']]['detected_any']:
            c['ids_missed'].append(m['id'])
        for g in groups:
            c['by_group'][g] += table[m['id']]['groups'][g]['detected']
    old = [g for g in groups if g != 'V']
    suite_rates = dict(caught=sum(table[m['id']]['detected_any'] for m in mut), of=len(mut),
                       missed=[m['id'] for m in mut if not table[m['id']]['detected_any']],
                       caught_by_T1_T4=sum(any(table[m['id']]['groups'][g]['detected'] for g in ('T1', 'T2', 'T3', 'T4'))
                                           for m in mut),
                       caught_by_T5_T6=sum(any(table[m['id']]['groups'][g]['detected'] for g in ('T5', 'T6'))
                                           for m in mut),
                       caught_by_old_groups=sum(any(table[m['id']]['groups'][g]['detected'] for g in old)
                                                for m in mut),
                       caught_only_by_V=[m['id'] for m in mut if table[m['id']]['detected_any'] and
                                         not any(table[m['id']]['groups'][g]['detected'] for g in old)])
    controls = {m['id']: dict(false_alarm=table[m['id']]['detected_any'],
                              groups=table[m['id']]['detected_groups'],
                              tests=[c['test'] for v in table[m['id']]['groups'].values() for c in v['changed']])
                for m in mutants if m['category'] == 'control' and m['id'] in table}
    by_test = {}
    for i, t in table.items():
        for g, v in t['groups'].items():
            for c in v['changed']:
                by_test.setdefault(f"{g}::{c['test']}", []).append(i)
    mismatches = [dict(id=i, group=g, predicted=v['predicted'], detected=v['detected'])
                  for i, t in table.items() for g, v in t['groups'].items()
                  if v['prediction_ok'] is False]
    n_firm = sum(v['prediction_ok'] is not None for t in table.values() for v in t['groups'].values())
    return dict(table=table, rates_by_group=rates, rates_by_category=cats, suite=suite_rates,
                controls=controls, catches_by_test=by_test, prediction_mismatches=mismatches,
                n_firm_predictions=n_firm)


def compare_v01(run):
    """v0.2: compare the v0.1 part of a run's summaries with B0 and B1 of out/mutation_v0_1.json.
    Returns, per reference run, the number of numbers compared, the number that differ (not
    bit-identical), the largest relative difference and the differing keys."""
    with open(os.path.join(ROOT, 'out', 'mutation_v0_1.json')) as f:
        ref = json.load(f)['runs']
    out = {}
    for rid in ('B0', 'B1'):
        n, diff, worst, keys, missing = 0, 0, 0.0, [], []
        for fx, rec in ref[rid]['fixtures'].items():
            if 'summary' not in rec:
                continue
            a = run['fixtures'].get(fx, {}).get('summary')
            if a is None:
                missing.append(fx)
                continue
            fa, fb = dict(_flatten(_strip_v03(a))), dict(_flatten(rec['summary']))
            for k, vb in fb.items():
                n += 1
                if k not in fa:
                    missing.append(f'{fx}.{k}')
                    continue
                va = fa[k]
                if va != vb:
                    diff += 1
                    keys.append(f'{fx}.{k}')
                    if isinstance(va, (int, float)) and isinstance(vb, (int, float)) and \
                            not isinstance(vb, bool):
                        worst = max(worst, abs(va - vb) / max(abs(vb), 1e-300))
                    else:
                        worst = math.inf
            extra = set(fa) - set(fb)
            if extra:
                missing.append(f'{fx}: {len(extra)} keys not in v0.1')
        out[rid] = dict(n_compared=n, n_different=diff, max_rel_diff=worst,
                        different_keys=keys[:50], missing=missing[:50])
    return out


