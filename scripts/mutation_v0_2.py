def _main(args, workdir):
    msets = {'v0.2': mutant_set('v0.2'), 'v0.1': mutant_set('v0.1')}
    designs = [] if args.baseline_only else args.design
    if args.check:
        for key in designs:
            kind, suite = DESIGNS[key]
            for m in msets[kind]:
                if args.only is not None and m['id'] not in args.only:
                    continue
                tmp = tempfile.mkdtemp(prefix=f"chk_{m['id']}_", dir=workdir)
                try:
                    _copy_tree(tmp, suite, workdir)
                    _apply(tmp, _patches_for(m, suite))
                    print(f"({key}) {suite} {m['id']}: patch applies and compiles")
                except Exception as exc:
                    print(f"({key}) {suite} {m['id']}: FAILED: {exc}")
                finally:
                    shutil.rmtree(tmp, ignore_errors=True)
        return
    suites = [args.baseline_only] if args.baseline_only else \
        sorted({DESIGNS[k][1] for k in designs}, key=list(SUITE_REFS).index)
    info = {s: suite_info(s) for s in suites}
    env = environment()
    jobs = []
    for s in suites:
        jobs += [(f'{s}/B0', s, []), (f'{s}/B1', s, [])]
    for key in designs:
        kind, suite = DESIGNS[key]
        for m in msets[kind]:
            if args.only is None or m['id'] in args.only:
                jobs.append((f"{suite}/{m['id']}", suite, _patches_for(m, suite)))
    for s in suites:
        _suite_tree(s, workdir)
    runs = {}
    t0 = time.time()
    print(f"{len(jobs)} runs on {args.jobs} workers; suites: " +
          ', '.join(f"{s} = {info[s]['commit'][:7]}" for s in suites), flush=True)
    with ThreadPoolExecutor(max_workers=args.jobs) as ex:
        futs = {ex.submit(run_one, i, s, p, workdir, args.fixture_timeout, args.run_timeout): i
                for i, s, p in jobs}
        for fut in futs:
            i = futs[fut]
            runs[i] = fut.result()
            print(f"[{time.time() - t0:7.1f}s] {i}: {runs[i].get('pytest_summary')}", flush=True)
    results = dict(designs={}, baselines={})
    for s in suites:
        b0, b1 = runs[f'{s}/B0'], runs[f'{s}/B1']
        det = all(_max_rel_change(b1, b0, g) in (0.0, None) for g in GROUPS) and \
            {k: v['outcome'] for k, v in b0['outcomes'].items()} == \
            {k: v['outcome'] for k, v in b1['outcomes'].items()}
        results['baselines'][s] = dict(
            deterministic=det, B0=b0.get('pytest_summary'), B1=b1.get('pytest_summary'),
            B1_vs_B0_max_rel_change={g: _max_rel_change(b1, b0, g) for g in GROUPS},
            vs_v01=dict(B0=compare_v01(b0), B1=compare_v01(b1)) if args.compare_v01 else None)
    for key in designs:
        kind, suite = DESIGNS[key]
        ms = [m for m in msets[kind] if args.only is None or m['id'] in args.only]
        results['designs'][key] = analyse(runs, suite, ms)
    if 'i' in results['designs'] and 'ii' in results['designs']:
        a, b = results['designs']['i']['table'], results['designs']['ii']['table']
        results['comparison_i_ii'] = {
            i: dict(v021=a[i]['detected_any'], v03=b[i]['detected_any'],
                    v021_groups=a[i]['detected_groups'], v03_groups=b[i]['detected_groups'])
            for i in a if i in b}
    write_outputs(args.out, env, info, runs, results, args, msets)
    for s, v in results['baselines'].items():
        cmp = v['vs_v01']
        print(f"{s} baselines: {v['B0']} / {v['B1']}; deterministic: {v['deterministic']}")
        if cmp:
            for b in ('B0', 'B1'):
                print(f"  {b} vs v0.1 B0: {cmp[b]['B0']['n_different']} of {cmp[b]['B0']['n_compared']} differ; "
                      f"vs v0.1 B1: {cmp[b]['B1']['n_different']} differ")
    for key, res in results['designs'].items():
        print(f"design ({key}) {DESIGNS[key]}: caught {res['suite']['caught']} of {res['suite']['of']}; "
              f"missed {res['suite']['missed']}; controls {res['controls']}")


if __name__ == '__main__':
    main()
