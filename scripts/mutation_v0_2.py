def _clean(x):
    """JSON-safe copy: numpy scalars -> Python, non-finite floats -> strings."""
    if isinstance(x, dict):
        return {str(k): _clean(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_clean(v) for v in x]
    if hasattr(x, 'item') and not isinstance(x, (str, bytes)):
        try:
            x = x.item()
        except (ValueError, AttributeError):
            return str(x)
    if isinstance(x, float) and not math.isfinite(x):
        return str(x)
    return x




def _git(*args):
    p = subprocess.run(['git', *args], cwd=ROOT, capture_output=True)
    if p.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)}: {p.stderr.decode()[:300]}")
    return p.stdout


def suite_info(suite):
    """v0.2: commit and tree hashes of the suite's source tree."""
    ref = SUITE_REFS[suite]
    commit = _git('rev-parse', f'{ref}^{{commit}}').decode().strip()
    trees = {p: _git('rev-parse', f'{commit}:{p}').decode().strip()
             for p in ('hank_limits', 'tests', 'pytest.ini')}
    return dict(ref=ref, commit=commit, trees=trees)


_TREE_CACHE = {}


def _suite_tree(suite, workdir):
    """v0.2: extract the suite's tree once (git archive) and return its directory."""
    if suite not in _TREE_CACHE:
        commit = suite_info(suite)['commit']
        d = tempfile.mkdtemp(prefix=f'suite_{suite}_', dir=workdir)
        data = _git('archive', '--format=tar', commit, 'hank_limits', 'tests', 'pytest.ini')
        with tarfile.open(fileobj=io.BytesIO(data)) as tf:
            tf.extractall(d, filter='data')
        _TREE_CACHE[suite] = d
    return _TREE_CACHE[suite]


def _copy_tree(dst, suite, workdir):
    src = _suite_tree(suite, workdir)
    for name in ('hank_limits', 'tests'):
        shutil.copytree(os.path.join(src, name), os.path.join(dst, name),
                        ignore=shutil.ignore_patterns('__pycache__'))
    shutil.copy(os.path.join(src, 'pytest.ini'), dst)


def _apply(dst, patches):
    for fname, old, new in patches:
        path = os.path.join(dst, 'hank_limits', fname)
        with open(path) as f:
            src = f.read()
        n = src.count(old)
        if n != 1:
            raise ValueError(f'{fname}: patch target occurs {n} times: {old[:60]!r}')
        with open(path, 'w') as f:
            f.write(src.replace(old, new))
    for fname in sorted({p[0] for p in patches}):
        py_compile.compile(os.path.join(dst, 'hank_limits', fname), doraise=True)


def _thread_env():
    env = dict(os.environ)
    for v in ('OMP_NUM_THREADS', 'OPENBLAS_NUM_THREADS', 'MKL_NUM_THREADS',
              'NUMBA_NUM_THREADS', 'VECLIB_MAXIMUM_THREADS'):
        env[v] = '1'
    return env


def run_one(run_id, suite, patches, workdir, fixture_timeout, run_timeout):
    tmp = tempfile.mkdtemp(prefix=f"mut_{run_id.replace('/', '_')}_", dir=workdir)
    try:
        _copy_tree(tmp, suite, workdir)
        _apply(tmp, patches)
        out = os.path.join(tmp, 'result.json')
        env = _thread_env()
        env.update(MUTATION_V0_2_OUT=out, MUTATION_V0_2_TIMEOUT=str(fixture_timeout),
                   PYTHONPATH=os.path.join(ROOT, 'scripts'), PYTHONDONTWRITEBYTECODE='1')
        t0 = time.time()
        try:
            p = subprocess.run([sys.executable, '-m', 'pytest', '-q', '-p', 'mutation_v0_2',
                                '-p', 'no:cacheprovider'], cwd=tmp, env=env,
                               capture_output=True, text=True, timeout=run_timeout)
            tail = p.stdout.strip().splitlines()[-1:] if p.stdout else []
            status = dict(returncode=p.returncode, pytest_summary=tail[0] if tail else '')
        except subprocess.TimeoutExpired:
            status = dict(returncode=None, pytest_summary=f'run stopped after {run_timeout} s')
        wall = time.time() - t0
        res = json.load(open(out)) if os.path.exists(out) else dict(outcomes={}, fixtures={})
        res.update(status, wall_s=wall)
        return res
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def _flatten(x, prefix=''):
    if isinstance(x, dict):
        for k, v in x.items():
            yield from _flatten(v, f'{prefix}{k}.')
    elif isinstance(x, list):
        for i, v in enumerate(x):
            yield from _flatten(v, f'{prefix}{i}.')
    else:
        yield prefix.rstrip('.'), x


